/**
 * Builds the audio manifest from whatever is in /public/audio.
 *
 * Usage: npm run assets:audio
 *
 * The tracks themselves are no longer in this repository — they are served
 * from object storage (see NEXT_PUBLIC_AUDIO_BASE_URL in asset-path.ts), and
 * src/lib/audio-manifest.ts is committed so a build never needs them. To
 * regenerate it, put the files back in public/audio first; the archive of both
 * encodings lives outside the repo.
 *
 * Name a file after its channel and a number — "Flow 1.m4a", "Still 2.m4a" —
 * and it becomes part of that channel's programme. The numbers only decide the
 * order, so they do not have to start at one or be contiguous.
 *
 * Durations are read from the files rather than typed by hand, because they are
 * what keeps listeners in the same place: every visitor works out where the
 * programme is from these numbers and their own clock, so a wrong one silently
 * pulls a channel out of sync for everybody.
 */

import { readdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { parseFile } from 'music-metadata';

const ROOT = path.resolve(import.meta.dirname, '..');
const AUDIO_DIR = path.join(ROOT, 'public/audio');
const OUT_FILE = path.join(ROOT, 'src/lib/audio-manifest.ts');

/** Must match the channel ids in src/lib/channels.ts. */
const CHANNELS = ['still', 'flow', 'momentum'];

const NAME = /^(still|flow|momentum)\s*(\d+)$/i;

const entries = await readdir(AUDIO_DIR);
const audioFiles = entries.filter((f) => /\.(mp3|m4a|ogg|opus|wav)$/i.test(f));

const tracks = [];
const ignored = [];

for (const file of audioFiles) {
  const stem = file.replace(/\.[^.]+$/, '');
  const match = NAME.exec(stem);
  if (!match) {
    ignored.push(file);
    continue;
  }
  const channel = match[1].toLowerCase();
  const order = Number.parseInt(match[2], 10);

  const meta = await parseFile(path.join(AUDIO_DIR, file));
  const duration = meta.format.duration;
  if (!duration || !Number.isFinite(duration) || duration <= 0) {
    throw new Error(`Could not read a duration from ${file}. Is it a complete audio file?`);
  }

  tracks.push({
    channel,
    order,
    file,
    // Spaces and any other awkward characters have to survive the trip.
    src: `/audio/${encodeURIComponent(file)}`,
    durationSeconds: Number(duration.toFixed(3)),
    title: meta.common.title ?? null,
  });
}

const byChannel = Object.fromEntries(
  CHANNELS.map((id) => [id, tracks.filter((t) => t.channel === id).sort((a, b) => a.order - b.order)]),
);

const empty = CHANNELS.filter((id) => byChannel[id].length === 0);
if (empty.length > 0) {
  throw new Error(
    `No audio found for: ${empty.join(', ')}.\n` +
      `Add a file named like "${empty[0][0].toUpperCase() + empty[0].slice(1)} 1.mp3" to public/audio.`,
  );
}

const lines = [
  '/**',
  ' * Generated by `npm run assets:audio` — do not edit by hand.',
  ' *',
  " * Each channel's programme, in order. Durations are read from the files",
  ' * themselves; they are what every visitor uses to work out where the shared',
  ' * programme currently is.',
  ' */',
  '',
  'export interface ManifestTrack {',
  '  src: string;',
  '  durationSeconds: number;',
  '  /** From the file\'s own tags, for the licensing note. Not shown in the UI. */',
  '  title: string | null;',
  '}',
  '',
  'export const AUDIO_MANIFEST: Record<string, readonly ManifestTrack[]> = {',
];

for (const id of CHANNELS) {
  lines.push(`  ${id}: [`);
  for (const t of byChannel[id]) {
    lines.push('    {');
    lines.push(`      src: ${JSON.stringify(t.src)},`);
    lines.push(`      durationSeconds: ${t.durationSeconds},`);
    lines.push(`      title: ${JSON.stringify(t.title)},`);
    lines.push('    },');
  }
  lines.push('  ],');
}

lines.push('};', '');

await writeFile(OUT_FILE, lines.join('\n'), 'utf8');

console.log(`Wrote ${path.relative(ROOT, OUT_FILE)}\n`);
for (const id of CHANNELS) {
  const list = byChannel[id];
  const total = list.reduce((sum, t) => sum + t.durationSeconds, 0);
  console.log(`  ${id.padEnd(9)} ${list.length} track(s), ${(total / 60).toFixed(1)} min`);
  for (const t of list) {
    console.log(`    - ${t.file} (${(t.durationSeconds / 60).toFixed(1)} min)`);
  }
}
if (ignored.length > 0) {
  console.log(`\n  Ignored (name them "<Channel> <n>" to include them):`);
  for (const f of ignored) console.log(`    - ${f}`);
}
