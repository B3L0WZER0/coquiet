/**
 * The journal's images:
 *
 * 1. Each photo in content/journal/images, encoded to public/journal/images in
 *    the same widths and formats as the rooms, and listed with its blurred
 *    placeholder in src/lib/journal/photo-manifest.ts.
 * 2. A link-preview card per post in public/journal/cards — the post's
 *    photograph cropped to 1200×630, with its title over it.
 *
 *   npm run assets:journal
 */
import { existsSync } from 'node:fs';
import { mkdir, readFile, readdir, stat, writeFile } from 'node:fs/promises';
import { join } from 'node:path';

import { ImageResponse } from 'next/og.js';
import React from 'react';
import sharp from 'sharp';

import { BACKGROUND_MANIFEST } from '../src/lib/background-manifest.ts';

const ROOT = join(import.meta.dirname, '..');
const CONTENT = join(ROOT, 'content/journal');
const PHOTO_SRC = join(CONTENT, 'images');
const PHOTO_OUT = join(ROOT, 'public/journal/images');
const CARD_OUT = join(ROOT, 'public/journal/cards');
const MANIFEST = join(ROOT, 'src/lib/journal/photo-manifest.ts');
const FONT_CACHE_DIR = join(import.meta.dirname, '.cache');
const WIDTHS = [640, 1024, 1600, 2048];
const WIDTH = 1200;
const HEIGHT = 630;

// 1. Photos

await mkdir(PHOTO_OUT, { recursive: true });
const photos = [];
for (const file of (await readdir(PHOTO_SRC)).filter((f) => f.endsWith('.png')).sort()) {
  const id = file.replace(/\.png$/, '');
  const source = join(PHOTO_SRC, file);
  const { width, height } = await sharp(source).metadata();
  const widths = WIDTHS.filter((w) => w <= width * 1.05);

  // Skip what is already newer than its source; avif at effort 6 is the slow part.
  const sourceTime = (await stat(source)).mtimeMs;
  const outputs = widths.flatMap((w) => [`${id}-${w}.avif`, `${id}-${w}.webp`]);
  const times = await Promise.all(outputs.map((f) => stat(join(PHOTO_OUT, f)).then((s) => s.mtimeMs, () => 0)));
  if (!times.every((t) => t > sourceTime)) {
    for (const w of widths) {
      const base = sharp(source).resize({ width: w, withoutEnlargement: true });
      await base.clone().avif({ quality: 58, effort: 6 }).toFile(join(PHOTO_OUT, `${id}-${w}.avif`));
      await base.clone().webp({ quality: 76 }).toFile(join(PHOTO_OUT, `${id}-${w}.webp`));
    }
  }

  const lqip = await sharp(source)
    .resize(32, Math.round((32 * height) / width), { fit: 'fill' })
    .blur(1.2)
    .webp({ quality: 40 })
    .toBuffer();
  photos.push({ id, widths, lqip: `data:image/webp;base64,${lqip.toString('base64')}` });
  console.log(`photo ${id}  ${widths.join('/')}`);
}

await writeFile(
  MANIFEST,
  `/** Generated by \`npm run assets:journal\` — do not edit by hand. */

export interface JournalPhotoEntry {
  id: string;
  widths: readonly number[];
  lqip: string;
}

export const JOURNAL_PHOTOS: readonly JournalPhotoEntry[] = ${JSON.stringify(photos, null, 2)};
`,
);

// 2. Cards

/** Same approach as generate-og-image.mjs: static .ttf, cached. */
async function googleFont(family, weight) {
  const file = join(FONT_CACHE_DIR, `${family.replace(/ /g, '')}-${weight}.ttf`);
  if (!existsSync(file)) {
    const css = await fetch(`https://fonts.googleapis.com/css2?family=${family.replace(/ /g, '+')}:wght@${weight}`, {
      headers: { 'User-Agent': 'Mozilla/4.0' },
    });
    const ttf = (await css.text()).match(/https:\/\/[^)]+\.ttf/)?.[0];
    if (!ttf) throw new Error(`${family} ${weight}: no static .ttf`);
    await mkdir(FONT_CACHE_DIR, { recursive: true });
    await writeFile(file, Buffer.from(await (await fetch(ttf)).arrayBuffer()));
  }
  return { name: family, data: await readFile(file), weight, style: 'normal' };
}

function frontMatter(source) {
  const meta = {};
  for (const line of /^---\n([\s\S]*?)\n---/.exec(source)[1].split('\n')) {
    const i = line.indexOf(':');
    if (i > 0) meta[line.slice(0, i).trim()] = line.slice(i + 1).trim();
  }
  return meta;
}

/** The post's own photo (centred), or its room's (through the room's focal point). */
async function crop({ image, room }) {
  let source;
  let focal = { focalX: 50, focalY: 50 };
  if (image) {
    source = join(PHOTO_SRC, `${image}.png`);
  } else {
    const r = BACKGROUND_MANIFEST.find((x) => x.id === room);
    if (!r) throw new Error(`No room "${room}"`);
    source = join(ROOT, `design-reference/${room}.png`);
    focal = r;
  }
  const { width, height } = await sharp(source).metadata();
  const h = Math.round(width / (WIDTH / HEIGHT));
  const region =
    h <= height
      ? { left: 0, top: Math.round((focal.focalY / 100) * (height - h)), width, height: h }
      : (() => {
          const w = Math.round(height * (WIDTH / HEIGHT));
          return { left: Math.round((focal.focalX / 100) * (width - w)), top: 0, width: w, height };
        })();
  return sharp(source).extract(region).resize(WIDTH, HEIGHT).jpeg({ quality: 90 }).toBuffer();
}

const fonts = [await googleFont('Playfair Display', 400), await googleFont('Inter', 300), await googleFont('Inter', 400)];
const e = React.createElement;
await mkdir(CARD_OUT, { recursive: true });

for (const file of (await readdir(CONTENT)).filter((f) => f.endsWith('.md'))) {
  const slug = file.replace(/^\d+-/, '').replace(/\.md$/, '');
  const meta = frontMatter(await readFile(join(CONTENT, file), 'utf8'));
  const photo = await crop(meta);

  const png = await new ImageResponse(
    e(
      'div',
      { style: { display: 'flex', width: '100%', height: '100%', position: 'relative' } },
      e('img', { src: `data:image/jpeg;base64,${photo.toString('base64')}`, width: WIDTH, height: HEIGHT, style: { position: 'absolute', inset: 0 } }),
      e('div', {
        style: {
          // Satori ignores `inset`; without a size the shade paints nothing.
          position: 'absolute',
          top: 0,
          left: 0,
          width: WIDTH,
          height: HEIGHT,
          // Heavy at the foot: some photographs are pale all the way down.
          background:
            'linear-gradient(to bottom, rgba(12,10,8,0.5) 0%, rgba(12,10,8,0.18) 30%, rgba(12,10,8,0.72) 58%, rgba(12,10,8,0.92) 100%)',
        },
      }),
      e(
        'div',
        {
          style: {
            position: 'relative',
            display: 'flex',
            flexDirection: 'column',
            justifyContent: 'space-between',
            width: '100%',
            height: '100%',
            padding: '56px 64px',
            color: '#f6f1e7',
          },
        },
        e('div', { style: { fontFamily: 'Inter', fontSize: 30, fontWeight: 300, letterSpacing: '0.08em' } }, 'coquiet · journal'),
        e('div', { style: { fontFamily: 'Playfair Display', fontSize: meta.title.length > 48 ? 58 : 68, lineHeight: 1.1, maxWidth: 1000 } }, meta.title),
      ),
    ),
    { width: WIDTH, height: HEIGHT, fonts },
  ).arrayBuffer();

  const jpeg = await sharp(Buffer.from(png)).jpeg({ quality: 82, mozjpeg: true }).toBuffer();
  await writeFile(join(CARD_OUT, `${slug}.jpg`), jpeg);
  console.log(`card ${slug}.jpg  ${(jpeg.length / 1024).toFixed(0)} KB`);
}
